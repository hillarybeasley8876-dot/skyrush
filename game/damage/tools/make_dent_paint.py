#!/usr/bin/env python3
"""Builds res://damage/dent_paint.gdshader from the shared car paint.

The damage unit needs the car paint with the damage layer of dossier 7.5 A (the dents, the
paint-scrape mask and the layers of the damaged paint). The shared paint belongs to the
shaders unit, so the damage paint is GENERATED from it: this script copies
res://shaders/car_paint.gdshader and adds the damage layer. Run it after every change of
the shared paint:

    python3 game/damage/tools/make_dent_paint.py

The hash of the source is written into the header, so tests/test_paint_sync.gd fails when
the two drift apart.
"""
import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
SOURCE = ROOT / "game" / "shaders" / "car_paint.gdshader"
TARGET = ROOT / "game" / "damage" / "dent_paint.gdshader"

HEADER = """// SKYRUSH - the car paint with the damage layer of dossier 7.5 A.
//
// GENERATED by game/damage/tools/make_dent_paint.py from res://shaders/car_paint.gdshader:
// the shared paint of the shaders unit plus:
//   * the dent field of res://damage/dent_field.gdshaderinc (8 dents in a ring buffer, in
//     the space of the CAR, so the paint, the trim and the door card move together),
//   * a per-pixel dent normal (the analytic gradient of the bowl) and a crumple noise,
//   * a car-space paint-scrape mask (a 1024x1024 atlas split in 5 regions) that blends the
//     paint to primer and to the bare substrate.
// The shared paint material is never touched: the damage unit installs this copy per car.
//
// source hash: {hash}
"""

UNIFORMS = """
// --- the damage (dossier 7.5 A) -------------------------------------------------------------------
uniform sampler2D damage_mask : filter_linear_mipmap, repeat_disable;
uniform float mask_enabled : hint_range(0.0, 1.0) = 0.0;
uniform float mask_gain : hint_range(0.0, 1.0) = 1.0;
uniform vec3 car_min = vec3(-0.95, 0.0, -2.30);   // the AABB of the car in car space
uniform vec3 car_size = vec3(1.90, 1.45, 4.60);
uniform vec4 mask_rect[5];   // the pixel rect of every region of the atlas
uniform vec3 primer_color : source_color = vec3(0.549, 0.561, 0.576);   // #8C8F93
uniform vec3 chip_rim_color : source_color = vec3(0.169, 0.173, 0.188); // #2B2C30
uniform vec3 substrate_color : source_color = vec3(0.082, 0.090, 0.106); // #15171B
uniform float substrate_metallic : hint_range(0.0, 1.0) = 0.25;
uniform float substrate_roughness : hint_range(0.0, 1.0) = 0.30;
uniform float substrate_twill : hint_range(0.0, 1.0) = 1.0;  // 1 = carbon twill, 0 = steel
uniform vec3 soot_color : source_color = vec3(0.102, 0.102, 0.110);     // #1A1A1C
uniform float scratch_lines : hint_range(0.0, 1000.0) = 300.0;  // the scratch lines per metre

// The layers of the paint (the value of the mask): the scuff of the clear coat, the
// chipped paint down to the primer, and the bare substrate.
const float LAYER_SCUFF = 0.25;
const float LAYER_PRIMER = 0.55;
const float LAYER_BARE = 0.72;
// The edge of the scrape is broken by the noise, so it has no straight lines.
const float EDGE_BREAKUP = 0.18;
// The scratches of the slide.
const float SCRATCH_STRENGTH = 0.3;
const float SCRATCH_NOISE = 45.0;
"""

HELPERS = """
// The plane of a region, in metres: the sides are (z, y), the front and the rear (x, y) and
// the roof (x, z). The scratches, the weave and the mottle are driven from it, so they
// follow the panel and not the axes of the world.
vec2 region_plane_m(vec3 car_pos, vec3 car_nrm, out float region) {
	vec3 n = normalize(car_nrm);
	region = 4.0;
	if (abs(n.y) > 0.7) {
		return vec2(car_pos.x, car_pos.z);
	}
	if (abs(n.x) > abs(n.z)) {
		region = n.x < 0.0 ? 0.0 : 1.0;
		return vec2(car_pos.z, car_pos.y);
	}
	region = n.z < 0.0 ? 2.0 : 3.0;
	return vec2(car_pos.x, car_pos.y);
}

// The origin of a region in the space of the car.
vec2 region_origin(float region) {
	if (region < 1.5) {
		return vec2(car_min.z, car_min.y);
	}
	if (region > 3.5) {
		return vec2(car_min.x, car_min.z);
	}
	return vec2(car_min.x, car_min.y);
}

// The size of a region in the space of the car.
vec2 region_size(float region) {
	if (region < 1.5) {
		return vec2(car_size.z, car_size.y);
	}
	if (region > 3.5) {
		return vec2(car_size.x, car_size.z);
	}
	return vec2(car_size.x, car_size.y);
}

// The UV of the atlas for a point of the car.
vec2 atlas_uv(vec3 car_pos, vec3 car_nrm) {
	float region = 0.0;
	vec2 plane = region_plane_m(car_pos, car_nrm, region);
	vec4 rect = mask_rect[int(region)];
	vec2 local = (plane - region_origin(region)) / max(region_size(region), vec2(0.01));
	return (rect.xy + clamp(local, 0.0, 1.0) * rect.zw) / 1024.0;
}

// A 3-octave FBM, used to break up the edge of the scrape.
float fbm3(vec3 p) {
	return value_noise(p) * 0.5 + value_noise(p * 2.03) * 0.3 + value_noise(p * 4.11) * 0.2;
}

// The micro scratches along the slide: the direction comes from the green channel of the
// mask, so the lines of every scrape follow the way the car slid. A line that is thinner
// than two pixels is faded to its mean, so it does not alias.
float scratch_lines_at(vec2 plane_m, float angle) {
	vec2 perp = vec2(-sin(angle), cos(angle));
	float phase = dot(plane_m, perp) * scratch_lines;
	float w = fwidth(phase);
	float fade = clamp(1.0 - (w - 0.5) * 2.0, 0.0, 1.0);
	float s = abs(sin(phase));
	float br = value_noise(vec3(plane_m * SCRATCH_NOISE, 0.0)) * 0.7 + 0.3;
	return mix(0.5, s * br, fade);
}

// The 2/2 twill of the carbon fibre (6 mm tows): the tows go over two and under two and
// the pattern is shifted one cell per row. The highlight of a tow is stretched along it.
float carbon_twill(vec2 m) {
	const float TOW = 0.006;
	vec2 g = m / TOW;
	vec2 cell = floor(g);
	vec2 f = fract(g);
	float phase = mod(cell.x + cell.y, 4.0);
	bool warp_up = phase < 2.0;
	float across = warp_up ? f.y : f.x;
	float along = warp_up ? f.x : f.y;
	float tow = cos((across - 0.5) * PI);
	// the weave is smaller than a pixel far away: it fades to its mean
	float px = max(fwidth(g.x), fwidth(g.y));
	float detail = 1.0 - smoothstep(0.35, 0.9, px);
	float shine = 0.86 + 0.28 * tow * (0.65 + 0.35 * sin(along * PI * 2.0));
	return mix(0.93, shine, detail);
}
"""

VERTEX = """
void vertex() {
	obj_pos = VERTEX;
	obj_nrm = NORMAL;
	VERTEX = dent_displace(VERTEX);
}
"""

CAR_SPACE = """
	// The point and the normal of this pixel in the space of the car: the mask, the weave
	// and the scratches of the paint are all in the space of the car.
	vec3 car_pos = (car_from_obj_matrix() * vec4(obj_pos, 1.0)).xyz;
	vec3 car_nrm = normalize((car_from_obj_matrix() * vec4(obj_nrm, 0.0)).xyz);
"""

DAMAGE_FRAGMENT = """
	// --- the damage (dossier 7.5 A) ---------------------------------------------------------------
	float region = 0.0;
	vec2 plane_m = region_plane_m(car_pos, car_nrm, region);
	float mask_value = 0.0;
	float slide = 0.0;
	float soot = 0.0;
	// The paint scrape is a layer of its own: it can be read without the dents.
	if (mask_enabled > 0.5) {
		// The red channel is the damage, the green one the direction of the slide.
		vec4 raw = texture(damage_mask, atlas_uv(car_pos, car_nrm));
		mask_value = clamp(raw.r * mask_gain, 0.0, 1.0);
		slide = raw.g * PI;
	}
	if (damage_enabled > 0.5) {
		// The bowl of the dent, bent per pixel, and the soot around its centre.
		vec3 obj_n = normalize(obj_nrm);
		float deepest = 0.0;
		float depth_of_deepest = 0.0;
		vec3 grad = dent_gradient(obj_pos, deepest, depth_of_deepest);
		// The crumple: the noise of a folded panel, on the normal as well. Its tilt is the
		// amplitude of the crumple over its wavelength, so it stays a crease and not a mess.
		if (deepest > 0.0) {
			float e = 0.02;
			float n0 = value_noise(obj_pos * crumple_scale);
			float nx = value_noise((obj_pos + vec3(e, 0.0, 0.0)) * crumple_scale);
			float ny = value_noise((obj_pos + vec3(0.0, e, 0.0)) * crumple_scale);
			float nz = value_noise((obj_pos + vec3(0.0, 0.0, e)) * crumple_scale);
			vec3 dn = vec3(nx - n0, ny - n0, nz - n0) / e;
			grad += dn * (CRUMPLE_MAX * deepest);
			soot = deepest * 0.22;
		}
		// The tilt of the bowl is capped at 25 degrees.
		float g = length(grad);
		if (g > 0.47) {
			grad *= 0.47 / g;
		}
		// The bent normal, in the space of the object, turned into the view space (the tangent
		// frame of the UVs is useless here: the Roadster paints its panels in millimetres).
		vec3 bent = normalize(obj_n - (grad - obj_n * dot(grad, obj_n)));
		NORMAL = normalize((VIEW_MATRIX * vec4(MODEL_NORMAL_MATRIX * bent, 0.0)).xyz);
	}
	// The layers of the paint: the scuff of the clear coat, the chipped paint, the bare
	// substrate and the soot around the dent (ART.md 5).
	if (mask_value > 0.02) {
		// The edge of the scrape is broken by the noise, so it has no straight lines.
		float breakup = (fbm3(car_pos * 80.0) - 0.5) * EDGE_BREAKUP;
		float m = clamp(mask_value + breakup * smoothstep(0.02, 0.08, mask_value), 0.0, 1.0);
		float t = max(fwidth(m), 0.001);
		if (m < LAYER_SCUFF) {
			// A scuffed clear coat is white and hazy, and it carries the scratches of the slide.
			float scuff = smoothstep(0.05 - t, LAYER_SCUFF + t, m);
			rough = mix(rough, min(rough + 0.35, 1.0), scuff);
			col = mix(col, vec3(0.88, 0.89, 0.90), scuff * 0.4);
			nrm.xy += vec2(scratch_lines_at(plane_m, slide) - 0.5) * SCRATCH_STRENGTH * scuff;
		} else if (m < LAYER_PRIMER) {
			float chip = smoothstep(LAYER_SCUFF - t, 0.45 + t, m);
			float mottle = 0.92 + 0.16 * fbm3(car_pos * 25.0);
			col = mix(col, primer_color * mottle, chip);
			rough = mix(rough, 0.70, chip);
			metal = mix(metal, 0.0, chip);
			float rim = smoothstep(0.22 - t, LAYER_SCUFF + t, m)
					* (1.0 - smoothstep(LAYER_SCUFF + t, 0.31 + t, m));
			col = mix(col, chip_rim_color, rim);
			nrm.xy += vec2(0.0, rim * 0.25);
		} else {
			float bare = smoothstep(LAYER_PRIMER - t, LAYER_BARE + t, m);
			vec3 sub = substrate_color;
			if (substrate_twill > 0.5) {
				sub *= carbon_twill(plane_m);
			} else {
				sub *= 0.9 + 0.2 * scratch_lines_at(plane_m, slide);
			}
			col = mix(col, sub, bare);
			metal = mix(metal, substrate_metallic, bare);
			rough = mix(rough, substrate_roughness, bare);
		}
		col = mix(col, soot_color, soot * smoothstep(0.02, 0.2, mask_value));
	}
"""


def main() -> int:
	text = SOURCE.read_text(encoding="utf-8")
	digest = hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]
	# the header of the shared file is replaced by the one of the damage paint
	body = text.split("shader_type spatial;", 1)[1]
	out = HEADER.format(hash=digest) + "shader_type spatial;" + body
	# the dent field, after the render modes
	marker = "global uniform float skyrush_wetness;"
	if marker not in out:
		print("make_dent_paint: the shared paint changed (no skyrush_wetness)")
		return 1
	out = out.replace(marker, '#include "res://damage/dent_field.gdshaderinc"\n\n' + marker, 1)
	# the damage uniforms, after the last uniform of the shared paint
	marker = "uniform bool use_livery = false;"
	if marker not in out:
		print("make_dent_paint: the shared paint changed (no use_livery)")
		return 1
	out = out.replace(marker, marker + "\n" + UNIFORMS, 1)
	# the helpers, before the vertex function
	vertex_at = out.index("void vertex() {")
	out = out[:vertex_at] + HELPERS.lstrip("\n") + "\n" + out[vertex_at:]
	# the vertex function with the dent
	old_vertex = """void vertex() {
	obj_pos = VERTEX;
	obj_nrm = NORMAL;
}"""
	if old_vertex not in out:
		print("make_dent_paint: the shared paint changed (the vertex function)")
		return 1
	out = out.replace(old_vertex, VERTEX.strip("\n"), 1)
	# the space of the car, at the top of the fragment
	old_fragment = "void fragment() {\n"
	if old_fragment not in out:
		print("make_dent_paint: the shared paint changed (no fragment)")
		return 1
	out = out.replace(old_fragment, old_fragment + CAR_SPACE.lstrip("\n"), 1)
	# the grime follows the height of the panel in the space of the car
	old_height = "float height = obj_pos.y + panel_offset_y;"
	if old_height not in out:
		print("make_dent_paint: the shared paint changed (the grime height)")
		return 1
	out = out.replace(old_height, "float height = car_pos.y;", 1)
	# the damage in the fragment, before the rain
	rain = "\t// Rain:"
	if rain not in out:
		print("make_dent_paint: the shared paint changed (no rain block)")
		return 1
	out = out.replace(rain, DAMAGE_FRAGMENT.strip("\n") + "\n\n" + rain, 1)
	# the clear coat is dulled by the damage
	out = out.replace(
		"CLEARCOAT = clearcoat_amount * (1.0 - grime);",
		"CLEARCOAT = clearcoat_amount * (1.0 - grime) * (1.0 - smoothstep(0.05, 0.3, mask_value));",
		1)
	TARGET.write_text(out, encoding="utf-8")
	print("make_dent_paint: wrote %s (source hash %s)" % (TARGET, digest))
	return 0


if __name__ == "__main__":
	sys.exit(main())

