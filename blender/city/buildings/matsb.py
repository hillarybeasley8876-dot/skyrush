"""Materials for the city block builder.

`SH_*` materials are placeholders: the Godot MaterialLibrary replaces them at runtime
with the shared shader library (CONTRACTS.md §2).  Everything else is a normal PBR
material built from the textures generated by blender/city/buildings/gen_textures.py.

The ORM map follows the glTF convention: R = ambient occlusion, G = roughness,
B = metallic.  The albedo is NOT multiplied by the ORM any more (that tinted every
surface by its own roughness); the AO is baked into the albedo by the generator and the
ORM keeps the raw values for the engine.
"""
import json
import os

import bpy

from lib import mats as libmats

TEX_DIR = os.path.expanduser("~/m/skyrush/game/assets/city/_tex")
_MANIFEST = None
_SIGN_SLOTS = None


def manifest():
    """Texture manifest (tile size in metres) written by gen_textures.py."""
    global _MANIFEST
    if _MANIFEST is None:
        path = os.path.join(TEX_DIR, "manifest.json")
        _MANIFEST = json.load(open(path)) if os.path.exists(path) else {}
    return _MANIFEST


def sign_slots():
    """Sign slot list (id, atlas, uv rect, colour) written by gen_textures.py."""
    global _SIGN_SLOTS
    if _SIGN_SLOTS is None:
        path = os.path.join(TEX_DIR, "signs.json")
        _SIGN_SLOTS = json.load(open(path)) if os.path.exists(path) else []
    return _SIGN_SLOTS


def tex_path(name, kind):
    """Path of a generated map (`<name>_<kind>.jpg|png`) or None."""
    for ext in ("jpg", "png"):
        p = os.path.join(TEX_DIR, "%s_%s.%s" % (name, kind, ext))
        if os.path.exists(p):
            return p
    return None


def image_path(name):
    """Path of a generated atlas image (`<name>.jpg|png`) or None."""
    for ext in ("jpg", "png"):
        p = os.path.join(TEX_DIR, "%s.%s" % (name, ext))
        if os.path.exists(p):
            return p
    return None


def _image(path, non_color):
    img = bpy.data.images.load(path, check_existing=True)
    if non_color:
        img.colorspace_settings.name = "Non-Color"
    return img


def _principled(mat):
    return next(n for n in mat.node_tree.nodes if n.type == "BSDF_PRINCIPLED")


def pbr_tex(name, tex_id, tile_m=None, roughness=0.8, tint=None, normal_strength=1.0,
            metallic=None, alpha=None, cull=False):
    """PBR material from a generated texture set (<id>_diff/_nor/_orm), UVs in metres.

    The ORM map drives roughness (green) and metallic (blue); the albedo keeps its own
    value.  `metallic` overrides the blue channel with a constant when the texture set
    is not metallic.
    """
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = _principled(mat)
    bsdf.inputs["Metallic"].default_value = 0.0 if metallic is None else metallic
    bsdf.inputs["Roughness"].default_value = roughness
    size = tile_m if tile_m is not None else manifest().get(tex_id, {}).get("size_m", 2.0)
    mapping = _mapping(nt, size)
    diff = tex_path(tex_id, "diff")
    orm = tex_path(tex_id, "orm")
    nor = tex_path(tex_id, "nor")
    if diff:
        d = _tex(nt, diff, False, mapping, (-700, 300))
        colour = d.outputs["Color"]
        if orm:
            o = _tex(nt, orm, True, mapping, (-700, 60))
            sep = nt.nodes.new("ShaderNodeSeparateColor")
            sep.location = (-450, 60)
            nt.links.new(o.outputs["Color"], sep.inputs["Color"])
            nt.links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
            if metallic is None:
                nt.links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
        if tint:
            mixc = nt.nodes.new("ShaderNodeMix")
            mixc.data_type = "RGBA"
            mixc.blend_type = "MULTIPLY"
            mixc.inputs["Factor"].default_value = 1.0
            mixc.inputs["B"].default_value = (*tint[:3], 1.0)
            nt.links.new(colour, mixc.inputs["A"])
            colour = mixc.outputs["Result"]
        nt.links.new(colour, bsdf.inputs["Base Color"])
    if alpha is not None:
        bsdf.inputs["Alpha"].default_value = alpha
        mat.surface_render_method = "BLENDED"
    if cull:
        mat.use_backface_culling = True
    if nor:
        n = _tex(nt, nor, True, mapping, (-700, -320))
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nm.location = (-420, -320)
        nm.inputs["Strength"].default_value = normal_strength
        nt.links.new(n.outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    return mat


def pbr_atlas(name, tex_id, roughness=0.6, metallic=0.0, normal_strength=1.0,
               cull=False):
    """A PBR material from an atlas set (the UVs are 0..1 per face, so no mapping).

    The prop sheet is an atlas: the cells carry the flat faces of the street
    clutter, and the sheet now also has a normal and an ORM map.
    """
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nt = mat.node_tree
    bsdf = _principled(mat)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    mapping = _mapping(nt, 1.0)
    diff = tex_path(tex_id, "diff") or image_path(tex_id)
    orm = tex_path(tex_id, "orm")
    nor = tex_path(tex_id, "nor")
    if diff:
        d = _tex(nt, diff, False, mapping, (-700, 300))
        colour = d.outputs["Color"]
        if orm:
            o = _tex(nt, orm, True, mapping, (-700, 60))
            sep = nt.nodes.new("ShaderNodeSeparateColor")
            sep.location = (-450, 60)
            nt.links.new(o.outputs["Color"], sep.inputs["Color"])
            nt.links.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
            nt.links.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
        nt.links.new(colour, bsdf.inputs["Base Color"])
    if nor:
        n = _tex(nt, nor, True, mapping, (-700, -320))
        nm = nt.nodes.new("ShaderNodeNormalMap")
        nm.location = (-420, -320)
        nm.inputs["Strength"].default_value = normal_strength
        nt.links.new(n.outputs["Color"], nm.inputs["Color"])
        nt.links.new(nm.outputs["Normal"], bsdf.inputs["Normal"])
    if cull:
        mat.use_backface_culling = True
    return mat


def _mapping(nt, size):
    """UV -> Mapping node: one texture repeat covers `size` metres.

    `size` is either a number (a square tile) or a (u, v) pair, so a texture that
    covers 3.00 x 1.30 m of wall is not stretched 2.3x on the vertical.
    """
    uv = nt.nodes.new("ShaderNodeUVMap")
    uv.location = (-1200, 0)
    uv.uv_map = "UVMap"
    mapping = nt.nodes.new("ShaderNodeMapping")
    mapping.location = (-1000, 0)
    if isinstance(size, (list, tuple)):
        su, sv = float(size[0]), float(size[1])
    else:
        su = sv = float(size)
    mapping.inputs["Scale"].default_value = (1.0 / max(su, 1e-4), 1.0 / max(sv, 1e-4), 1.0)
    nt.links.new(uv.outputs["UV"], mapping.inputs["Vector"])
    return mapping


def _tex(nt, path, non_color, mapping, loc):
    node = nt.nodes.new("ShaderNodeTexImage")
    node.image = _image(path, non_color)
    node.location = loc
    nt.links.new(mapping.outputs["Vector"], node.inputs["Vector"])
    return node


def emissive_tex(name, image_name, strength=0.9, roughness=0.4, cull=False):
    """Emissive material from a generated atlas image (UV 0..1 per face)."""
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    path = tex_path(image_name, "diff") or image_path(image_name)
    if path is None:
        return placeholder(name, (0.2, 0.2, 0.2, 1.0), roughness)
    mat = libmats.image_material(name, path, roughness=roughness,
                                 emission_strength=strength)
    if cull:
        mat.use_backface_culling = True
    return mat


def image_mat(name, image_name, roughness=0.6, strength=0.0, cull=False):
    """A material from a single atlas image (no emission): cloth, plaques, decals."""
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    path = tex_path(image_name, "diff") or image_path(image_name)
    if path is None:
        return placeholder(name, (0.3, 0.3, 0.3, 1.0), roughness)
    mat = libmats.image_material(name, path, roughness=roughness,
                                 emission_strength=strength)
    if cull:
        mat.use_backface_culling = True
    return mat


def emissive_pair(name, diff_id, emit_id, strength=1.0, cull=True):
    """A material with a colour map and a separate emission map (the far LOD windows)."""
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mat = pbr_tex(name, diff_id, tile_m=1.0, roughness=0.6)
    nt = mat.node_tree
    bsdf = _principled(mat)
    path = tex_path(emit_id, "emit") or image_path(emit_id)
    if path is None:
        return mat
    node = nt.nodes.new("ShaderNodeTexImage")
    node.image = _image(path, False)
    node.location = (-500, 200)
    nt.links.new(node.outputs["Color"], bsdf.inputs["Emission Color"])
    bsdf.inputs["Emission Strength"].default_value = strength
    if cull:
        mat.use_backface_culling = True
    return mat


def placeholder(name, color=(0.4, 0.4, 0.4, 1.0), roughness=0.6, metallic=0.0):
    """A material whose name starts with SH_: replaced by the runtime shader library."""
    mat = bpy.data.materials.get(name)
    if mat is not None:
        return mat
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    bsdf = _principled(mat)
    bsdf.inputs["Base Color"].default_value = color
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    return mat
